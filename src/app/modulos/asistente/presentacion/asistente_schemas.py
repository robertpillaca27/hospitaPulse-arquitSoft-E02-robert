"""Request and response models for open-ended assistant messages."""

from pydantic import BaseModel, ConfigDict, Field, field_validator


class PreguntaAsistenteRequest(BaseModel):
    """A single user question; prior chat messages are not accepted."""

    model_config = ConfigDict(extra="forbid")

    pregunta: str = Field(min_length=1, max_length=1200)

    @field_validator("pregunta")
    @classmethod
    def trim_question(cls, value: str) -> str:
        """Reject whitespace-only questions after normalizing surrounding spaces."""
        normalized = value.strip()
        if not normalized:
            raise ValueError("La pregunta no puede estar vacía.")
        return normalized


class RespuestaAsistenteResponse(BaseModel):
    """An answer generated by the configured language model."""

    respuesta: str = Field(min_length=1, max_length=6000)
